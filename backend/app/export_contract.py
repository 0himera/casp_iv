"""Run from backend/: uv run python -m app.export_contract."""

import json

from .config import REPOSITORY_ROOT
from .main import app


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(typescript(child) for child in schema["anyOf"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    kind = schema.get("type")
    if kind == "object":
        if not schema.get("properties") and isinstance(schema.get("additionalProperties"), dict):
            return f"Record<string, {typescript(schema['additionalProperties'])}>"
        fields = []
        for name, child in schema.get("properties", {}).items():
            optional = "" if name in schema.get("required", []) else "?"
            fields.append(f"  {name}{optional}: {typescript(child)};")
        return "{\n" + "\n".join(fields) + "\n}"
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    schema = app.openapi()
    target = REPOSITORY_ROOT / "api"
    (target / "public-data.openapi.json").write_text(
        json.dumps(schema, ensure_ascii=False, indent=2) + "\n"
    )
    types = "// Generated by: cd backend && uv run python -m app.export_contract\n\n"
    for name, model in schema["components"]["schemas"].items():
        types += f"export type {name} = {typescript(model)};\n\n"
    (target / "public-data.types.ts").write_text(types.rstrip() + "\n")


if __name__ == "__main__":
    main()
