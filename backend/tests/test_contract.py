import json

from app.config import REPOSITORY_ROOT
from app.export_contract import typescript
from app.main import app


def test_exported_openapi_matches_runtime():
    schema = json.loads((REPOSITORY_ROOT / "api/public-data.openapi.json").read_text())
    assert schema == app.openapi()


def test_exported_types_match_openapi():
    schema = app.openapi()
    expected = "// Generated by: cd backend && uv run python -m app.export_contract\n\n"
    for name, model in schema["components"]["schemas"].items():
        expected += f"export type {name} = {typescript(model)};\n\n"
    assert (REPOSITORY_ROOT / "api/public-data.types.ts").read_text() == expected.rstrip() + "\n"
